"""Generate js/decor-icons.js from line icons:
- Lucide (lucide-static, ISC License);
- IconOven (MIT License) and Lucide Lab (ISC License), via the Iconify API, for the
  pieces Lucide lacks (Santa hat, stocking, sack, handcuffs, pet bowl, owl).

Every SVG element is converted to a path string so the canvas renderer can
draw it with Path2D. Run from the repository root: python tools/build_icons.py
"""
import json
import pathlib
import re
import urllib.request
import xml.etree.ElementTree as ET

VERSION = "1.81.0"
ICONS = [
    "tree-pine", "star", "sparkles", "snowflake", "gift", "candy-cane", "bell",
    "wand-sparkles", "moon-star", "footprints", "paw-print", "bone", "heart",
    "zap", "shield", "rainbow", "cloud", "music", "mic-vocal", "crown",
    "angry", "frown", "cookie", "gem", "lollipop", "flower-2",
    # magic school
    "book-open", "book-marked", "scroll", "feather", "flask-round",
    # princesses and fairies
    "castle", "wand",
    # cops and robbers
    "siren", "fingerprint", "venetian-mask", "search", "key-round", "car-front",
]
# our name -> (Iconify prefix, icon name, indexes of drawn elements to drop)
ICONIFY = {
    "santa-hat": ("iconoven", "santa-hat", []),
    "christmas-stocking": ("iconoven", "christmas-stocking", []),
    "sack": ("iconoven", "seed-sack", [1]),  # Santa's sack: the seed mark is removed
    "christmas-tree": ("iconoven", "christmas-tree", []),
    "handcuffs": ("iconoven", "handcuffs", []),
    "pet-bowl": ("iconoven", "pet-bowl", []),
    "owl": ("lucide-lab", "owl", []),
}
CREDIT = {"iconoven": "IconOven, MIT", "lucide-lab": "Lucide Lab, ISC"}
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "js" / "decor-icons.js"


def num(v: str) -> float:
    return float(v)


def fmt(x: float) -> str:
    s = f"{x:.3f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def to_path(el: ET.Element) -> str:
    tag = el.tag.split("}")[-1]
    a = el.attrib
    if tag == "path":
        return a["d"]
    if tag == "circle":
        cx, cy, r = num(a["cx"]), num(a["cy"]), num(a["r"])
        return (f"M{fmt(cx - r)} {fmt(cy)}a{fmt(r)} {fmt(r)} 0 1 0 {fmt(2 * r)} 0"
                f"a{fmt(r)} {fmt(r)} 0 1 0 {fmt(-2 * r)} 0Z")
    if tag == "ellipse":
        cx, cy, rx, ry = num(a["cx"]), num(a["cy"]), num(a["rx"]), num(a["ry"])
        return (f"M{fmt(cx - rx)} {fmt(cy)}a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(2 * rx)} 0"
                f"a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(-2 * rx)} 0Z")
    if tag == "line":
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if tag in ("polyline", "polygon"):
        pts = re.split(r"[\s,]+", a["points"].strip())
        pairs = [f"{pts[i]} {pts[i + 1]}" for i in range(0, len(pts) - 1, 2)]
        d = "M" + "L".join(pairs)
        return d + ("Z" if tag == "polygon" else "")
    if tag == "rect":
        x, y = num(a.get("x", "0")), num(a.get("y", "0"))
        w, h = num(a["width"]), num(a["height"])
        rx = num(a.get("rx", a.get("ry", "0")))
        if rx <= 0:
            return f"M{fmt(x)} {fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z"
        return (f"M{fmt(x + rx)} {fmt(y)}h{fmt(w - 2 * rx)}a{fmt(rx)} {fmt(rx)} 0 0 1 {fmt(rx)} {fmt(rx)}"
                f"v{fmt(h - 2 * rx)}a{fmt(rx)} {fmt(rx)} 0 0 1 {fmt(-rx)} {fmt(rx)}"
                f"h{fmt(-(w - 2 * rx))}a{fmt(rx)} {fmt(rx)} 0 0 1 {fmt(-rx)} {fmt(-rx)}"
                f"v{fmt(-(h - 2 * rx))}a{fmt(rx)} {fmt(rx)} 0 0 1 {fmt(rx)} {fmt(-rx)}Z")
    raise ValueError(f"unsupported element {tag}")


def main() -> None:
    lines = [
        f"// Generated by tools/build_icons.py from lucide-static {VERSION} (ISC License), IconOven (MIT) and Lucide Lab (ISC).",
        "// Each icon is a list of SVG path strings in a 24x24 box, drawn as strokes.",
        "export const ICONS = {",
    ]
    for name in ICONS:
        url = f"https://cdn.jsdelivr.net/npm/lucide-static@{VERSION}/icons/{name}.svg"
        req = urllib.request.Request(url, headers={"User-Agent": "icon-fetch/1.0"})
        with urllib.request.urlopen(req, timeout=60) as r:
            svg = r.read().decode("utf-8")
        svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
        root = ET.fromstring(svg)
        paths = [to_path(el) for el in root]
        body = ", ".join("'" + p.replace("'", "") + "'" for p in paths)
        lines.append(f"  '{name}': [{body}],")
    for name, (prefix, icon, drop) in ICONIFY.items():
        url = f"https://api.iconify.design/{prefix}.json?icons={icon}"
        req = urllib.request.Request(url, headers={"User-Agent": "icon-fetch/1.0"})
        with urllib.request.urlopen(req, timeout=60) as r:
            data = json.loads(r.read().decode("utf-8"))
        svg = f'<svg xmlns="http://www.w3.org/2000/svg">{data["icons"][icon]["body"]}</svg>'
        elements = [el for el in ET.fromstring(svg).iter() if el.tag.split("}")[-1] in
                    ("path", "circle", "ellipse", "line", "polyline", "polygon", "rect")]
        paths = [to_path(el) for i, el in enumerate(elements) if i not in drop]
        body = ", ".join("'" + p.replace("'", "") + "'" for p in paths)
        lines.append(f"  '{name}': [{body}], // {prefix}:{icon} ({CREDIT[prefix]})")
    lines.append("};")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(ICONS) + len(ICONIFY)} icons -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
